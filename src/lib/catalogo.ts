export const GRUPPI_CATALOGO = Object.keys(LIBRERIA)

export const CATALOGO: EsercizioCatalogo[] = Object.entries(LIBRERIA).flatMap(([gruppo, voci]) =>
  voci.map(([nome, attrezzo, tipo]) => ({ nome, gruppo, attrezzo, tipo: tipo ?? (gruppo === 'Cardio' ? 'cardio' : 'ripetizioni') })),
)

/** Nome senza la parte tra parentesi: "Pressa 45° (leg press)" → "pressa 45" */
const chiave = (nome: string) => normalizzaNome(nome.replace(/\([^)]*\)/g, ' '))

const PER_NOME = new Map<string, EsercizioCatalogo>()
for (const e of CATALOGO) {
  PER_NOME.set(normalizzaNome(e.nome), e)
  PER_NOME.set(chiave(e.nome), e)
  // anche il nome tra parentesi: "pec deck", "leg press", "hammer curl"…
  const tra = /\(([^)]*)\)/.exec(e.nome)?.[1]
  if (tra) PER_NOME.set(normalizzaNome(tra), e)
}

export function cercaNelCatalogo(nome: string): EsercizioCatalogo | undefined {
  return PER_NOME.get(normalizzaNome(nome)) ?? PER_NOME.get(chiave(nome))
}

/** Regole per indovinare il gruppo di un esercizio scritto a mano (in ordine: le più specifiche prima) */
const REGOLE: [RegExp, string][] = [
  [/tapis|treadmill|corsa|camminata|cyclette|bici|bike|spinning|ellittica|vogatore|rower|stepper|stair|nuoto|salto della corda|skierg|hiit/, 'Cardio'],
  [/stretching|mobilita|foam|yoga/, 'Mobilità'],
  [/\bcalf|polpacc/, 'Polpacci'],
  [/(curl|flessioni) d[ie]l? polso|wrist|avambracc|hand ?grip/, 'Avambracci'],
  [/leg curl|nordic|stacco rumeno|gambe tese|good morning|femoral|hamstring|glute ham/, 'Femorali'],
  [/hip thrust|glute|ponte|slanci|abdu|addu|clamshell|sumo|pull through|donkey kick|monster walk|frog pump/, 'Glutei'],
  [/\bcurl|bicip|martello|hammer|scott/, 'Bicipiti'],
  [/french|push ?down|tricip|kickback|estensioni|presa stretta|jm press|\bdip su panca/, 'Tricipiti'],
  [/squat|pressa|leg press|leg extension|affond|step ?up|lunge|quadric/, 'Quadricipiti'],
  [/lento|military|shoulder press|arnold|alzate|face pull|tirate|upright|scrollat|shrug|deltoid|spall|reverse pec|rotazioni esterne|y raise|push press|landmine/, 'Spalle'],
  [/trazion|pull ?up|chin ?up|\blat\b|pull ?down|pulley|rematore|\brow\b|stacco|rack pull|iperestens|hyperext|superman|dorso|lombar/, 'Dorso'],
  [/panca|chest|croci|pec ?deck|pectoral|push ?up|piegament|\bdip|pullover|squeeze|petto/, 'Petto'],
  [/crunch|plank|addom|sit ?up|leg raise|sollevamento (gambe|ginocchia)|russian|ab wheel|hollow|twist|pallof|woodchop|v up|dead bug|mountain|toes to bar|dragon flag|vacuum/, 'Addome'],
  [/burpee|swing|thruster|clean|snatch|strappo|girata|slancio|get up|farmer|wall ball|slam|battle|box jump|sled|slitta|man maker|jumping jack/, 'Total body'],
]

export function indovinaGruppo(nome: string): string | undefined {
  const trovato = cercaNelCatalogo(nome)
  if (trovato) return trovato.gruppo
  const n = normalizzaNome(nome)
  return REGOLE.find(([re]) => re.test(n))?.[1]
}
